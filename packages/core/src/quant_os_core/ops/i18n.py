STRINGS: dict[str, dict[str, str]] = {"en": EN, "ur": UR, "ar": AR}


def normalize(lang: str | None) -> str:
    """``"ur-PK"`` -> ``"ur"``; anything unknown falls back to English."""

    code = (lang or "").strip().lower().replace("_", "-").split("-")[0]
    return code if code in STRINGS else "en"


def strings(lang: str | None) -> dict[str, str]:
    """All UI strings for ``lang`` (English for unknown codes or missing keys)."""

    code = normalize(lang)
    return {**EN, **STRINGS[code]}


def bundle(lang: str | None) -> dict[str, object]:
    """What ``GET /api/i18n`` returns: the strings plus direction and speech locale."""

    code = normalize(lang)
    return {
        "lang": code,
        "dir": "rtl" if code in RTL else "ltr",
        "speech": SPEECH_LOCALES[code],
        "strings": strings(code),
    }
